-- Update PIPELINE_METADATA with current run timestamp
-- Purpose: Records the current timestamp as the last successful execution time
--          so the next incremental extraction (FR-005) only picks up records
--          modified after this point
UPDATE IDEA_2_DB.PUBLIC.PIPELINE_METADATA
SET
    LAST_SUCCESSFUL_RUN_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    LAST_RUN_STATUS = 'SUCCESS',
    LAST_RUN_MESSAGE = 'Pipeline completed successfully',
    UPDATED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHERE PIPELINE_NAME = 'AEROSPACE_PARTS_PIPELINE';